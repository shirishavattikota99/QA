GUIDE = """AFFILIATE + TRANSACTIONS (CROSS-DOMAIN) RULES

How to attribute money to an affiliate
- Primary way: transactions.affiliateId (and transactions.affiliateChannelId) carry the player's affiliate.
  Always $match {"affiliateId": {"$exists": True, "$ne": None}} on transactions before grouping by affiliate.
- Fallback when that returns nothing: group transactions by playerId, $lookup players, and use players.affiliateId.
- Registrations always come from players (affiliateId, createdAt), never from transactions.
- Ready-made lifetime numbers exist: players.totalDepositAmount / totalDepositCount per player, and
  affiliateChannels.signupCount / ftdCount / qFtdCount / totalDepositAmount / totalEarnings per channel.

Typical metrics per affiliate (build them with $group + $cond, one pass over transactions)
- deposits = Payment/Deposit/Success amount; withdrawals = Payment/Withdraw/Success amount;
  net deposits = deposits - withdrawals; unique depositors = size of $addToSet playerId;
  average deposit per depositor = deposits / unique depositors; FTDs = isFtd True deposits;
  GGR = Game/Real bets - wins; chargebacks / refunds = status Chargeback / Refunded.
- Conversion rate = depositing players / registered players (players.totalDepositCount > 0 means the player deposited).
- Period comparison (this month vs last month): one $group with two $cond sums, then compute the change.
- Share of total: $group by affiliate, then $group null with $push, $unwind, divide by the total.

How to build the query
- Pick the root collection from the main subject: money per affiliate -> transactions; registrations or
  conversion per affiliate -> players; channel totals -> affiliateChannels.
- Filter and $group first, then $sort / $limit, and only then $lookup affiliates (and players) for names.
- After $limit use "$unwind": {"path": "...", "preserveNullAndEmptyArrays": True}; always show names, not ids.
- Apply a period only when the question gives one, and apply it to every money metric in that question.
- A question with several independent asks is split by the application; answer each part with its own single pipeline."""

